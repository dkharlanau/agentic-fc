"""Opt-in, bounded football telemetry; never copy raw requests or chat.

Recorded coordinates are inputs, not surveyed pitch geometry. An emitted action
is an intent, not evidence that a pass arrived or a shot was saved.
"""
import json
import math

from mid_fast_v1.engine import unwrap


def number(value):
    if type(value) in (int, float) and math.isfinite(value) and abs(value) <= 1_000_000:
        return round(value, 6)
    return None


def vector(value):
    if not isinstance(value, dict):
        return None
    return {key: number(value[key]) for key in ('x', 'y', 'z') if key in value}


def identity(value):
    return value if value in tuple('agentId_' + str(i) for i in range(5)) else None


def side(value):
    return value if type(value) is int and value in (0, 1) else None


def team(value):
    return value if value in ('home', 'away') else None


def boolean(value):
    return value if type(value) is bool else None


def action(value, current=False):
    # Engine action names observed in owned match logs. Unknown vocabulary is
    # explicitly omitted rather than treating arbitrary text as safe telemetry.
    known = ('IDLE', 'MOVING', 'DRIBBLING', 'SHOOTING', 'TACKLING', 'PASSING') if current else (
        'StayNearGoal', 'GoalkeeperJump', 'ChaseBall', 'AdvanceToGoalWithBall',
        'FindOpenSpace', 'InterceptBallCarrier', 'PressureBallCarrier', 'CoverZone',
        'MoveToTarget', 'MoveToPredictedBall', 'MarkNearestOpponent')
    return value if value in known else None


def snapshot(payload, commands, audit, handler_unix_ns):
    root = unwrap(payload)
    gs = root.get('gameState', {})
    if not isinstance(gs, dict):
        return {'schema': 1, 'omitted': 'invalid_game_state'}
    players = gs.get('players')
    rows = []
    if isinstance(players, list) and len(players) <= 10:
        for player in players:
            if not isinstance(player, dict):
                continue
            rows.append({
                'teamCode': team(player.get('teamCode')),
                'agentId': identity(player.get('agentId')),
                'position': vector(player.get('position')),
                'velocity': vector(player.get('velocity')),
                'stamina': number(player.get('stamina')),
                'orientation': number(player.get('orientation')),
                'hasBall': boolean(player.get('hasBall')),
                'isSprinting': boolean(player.get('isSprinting')),
                'currentAction': action(player.get('currentAction'), current=True),
                'lastAction': action(player.get('lastAction')),
            })
    ball = gs.get('ball') if isinstance(gs.get('ball'), dict) else {}
    phase = gs.get('playMode')
    phases = ('PLAY_ON', 'OPEN_PLAY', 'KICK_OFF', 'FREE_KICK', 'GOAL_KICK',
              'CORNER_KICK', 'THROW_IN', 'HALF_TIME', 'FULL_TIME', 'RESETTING')
    score = gs.get('score') if isinstance(gs.get('score'), dict) else {}
    # Commands are generated by our validated engine, but still project fields
    # rather than copying arbitrary dictionaries into a log.
    intents = []
    for command in commands[:1]:
        params = command.get('parameters', {})
        intent = {'playerId': 2, 'commandType': command.get('commandType'),
                  'duration': number(command.get('duration')), 'parameters': {}}
        for key in ('target_player_id', 'target_x', 'target_y', 'power', 'stance', 'intensity'):
            if key in params:
                intent['parameters'][key] = number(params[key])
        for key in ('sprint', 'aggressive'):
            if key in params:
                intent['parameters'][key] = boolean(params[key])
        for key, allowed in (('type', ('GROUND', 'AERIAL', 'THROUGH')),
                             ('aim_location', ('TL', 'TR', 'BL', 'BR', 'CENTER')),
                             ('tightness', ('LOOSE', 'TIGHT'))):
            if params.get(key) in allowed:
                intent['parameters'][key] = params[key]
        intents.append(intent)
    result = {'schema': 1, 'handlerUnixNs': handler_unix_ns,
              'tick': number(gs.get('tick')), 'gameTime': number(gs.get('gameTime')),
              'teamId': side(root.get('teamId')), 'observerPlayerId': 2,
              'playMode': phase if phase in phases else None,
              'score': {k: number(score.get(k)) for k in ('home', 'away')},
              'inputPlayerCount': len(players) if isinstance(players, list) else None,
              'players': rows,
              'ball': {'position': vector(ball.get('position')),
                       'velocity': vector(ball.get('velocity')),
                       'isFree': boolean(ball.get('isFree')),
                       'possessionTeamCode': team(ball.get('possessionTeamCode')),
                       'possessionTeamId': side(ball.get('possessionTeamId')),
                       'possessionAgentId': identity(ball.get('possessionAgentId')),
                       'possessionPlayerId': number(ball.get('possessionPlayerId'))},
              'ownIntent': intents,
              'frame': audit.get('frame'), 'reason': audit.get('reason'),
              'physicalActionOutcome': None}
    if len(json.dumps(result, allow_nan=False).encode('utf-8')) > 8192:
        return {'schema': 1, 'omitted': 'size_budget'}
    return result
